/**
 * Ударения церковнославянских и архаичных слов в цитатах из Евангелия и богослужебных текстов («+аще», «+иже»,
 * «гряд+ет», «х+ощет», «б+ыти»). Словарь собрал mr430 (4PDA, тема TeraTTS): только формы, что на деле
 * встречались в книгах и звучали неверно; ударения сверены по Евангелию и Апостолу гражданским шрифтом
 * с ударениями (azbyka.ru). Пополняется по мере новых случаев.
 *
 * Чисто церковные слова («аще», «иже», «еси», «глаголю») ставятся всегда — в современном тексте их нет.
 * Слова, которые есть и в нынешнем языке, но звучат там иначе или пишутся с «ё» («буди» — «Буди́ его!»,
 * «держатся», «грядет», «мене», «на сём свете»), — только в предложении, где есть и чисто церковное слово,
 * то есть в цитате. Слова, где ударение уже стоит (правила пользователя, книга с ударениями), не трогаются.
 */
