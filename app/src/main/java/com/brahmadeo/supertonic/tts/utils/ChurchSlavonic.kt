    // есть и в нынешнем языке: только рядом с чисто церковным словом
    private val MODERN = setOf(
        "сём", "сем", "мене", "буди", "держите", "держатся", "отпустите", "грядет", "привлечет",
        "паче", "сие", "адова", "связана", "связано", "разрешено", "разрешена", "свяжете",
        "отпустится", "отпустятся", "отметается", "приемлет", "приемлете",
    )

    private val stressed: Map<String, String> by lazy {
        val m = HashMap<String, String>()
        for (line in LIST.lineSequence()) {
            val f = line.trim().split(Regex("\\s+"))
            if (f.size < 2 || f[0].startsWith("#")) continue
            m[f[0].replace("+", "").lowercase()] = f[1]
        }
        m
    }

    private val word = Regex("[А-Яа-яЁё+́̀]+")

    /** Слово с ударением из словаря, буквы — в регистре исходного («Аще» → «+Аще»). */
    private fun cased(original: String, s: String): String {
        val sb = StringBuilder(s.length)
        var i = 0
        for (c in s) {
            if (c == '+') { sb.append('+'); continue }
            val o = original.getOrNull(i++)
            sb.append(if (o != null && o.isUpperCase()) c.uppercaseChar() else c)
        }
        return sb.toString()
    }

    fun apply(text: String): String {
        val map = stressed
        val found = word.findAll(text).filter { it.value.lowercase() in map }.toList()
        if (found.isEmpty()) return text
        val church = found.any { it.value.lowercase() !in MODERN }
        val sb = StringBuilder(text.length + 8)
        var at = 0
        for (m in found) {
            val w = m.value
            if (w.indexOf('+') >= 0 || w.indexOf('́') >= 0 || w.indexOf('̀') >= 0) continue
            val low = w.lowercase()
            if (low in MODERN && !church) continue
            sb.append(text, at, m.range.first).append(cased(w, map.getValue(low)))
            at = m.range.last + 1
        }
        if (at == 0) return text
        return sb.append(text, at, text.length).toString()
    }
}
