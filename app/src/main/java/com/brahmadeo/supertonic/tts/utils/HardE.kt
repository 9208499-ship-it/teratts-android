package com.brahmadeo.supertonic.tts.utils

/**
 * «Э» вместо «е» в заимствованных словах, где по норме согласный перед «е» твёрдый: «каф[э]», «от[э]ль»,
 * «компьют[э]р», «т[э]ннис» (tolyos, 11.2026). Голос читал их мягко, как пишется. Каждая форма слова
 * («отеля», «моделями») — из списка; ставится после словаря ударений (он ищет слово в обычном написании),
 * ударение остаётся на месте. Слова, что по норме звучат мягко (меню, кофе, термин, теория, демократия,
 * кодекс, прогресс), не берутся. Список — tools/hard_lemmas.txt, формы делает tools/gen_hard.py (pymorphy3);
 * формы, совпадающие с другим словом («теста» — тесто), выкинуты. «Э» в строке — буква, что читается как «э».
 */
object HardE {
    private val map: Map<String, String> by lazy {
        val m = HashMap<String, String>(2048)
        for (l in LIST.lineSequence()) {
            val s = l.trim()
            if (s.isNotEmpty()) m[s.replace('Э', 'е')] = s.replace('Э', 'э')
        }
        m
    }

    private val WORD = Regex("[А-Яа-яЁё+́]+")

    fun apply(text: String): String {
        val m = map
        return WORD.replace(text) { r ->
            val w = r.value
            val plain = w.filter { it != '+' && it != '́' }.lowercase().replace('ё', 'е')
            val hard = m[plain] ?: return@replace w
            val sb = StringBuilder(w.length)
            var j = 0
            for (c in w) {
                if (c == '+' || c == '́') { sb.append(c); continue }
                val h = hard[j++]
                sb.append(if (h == 'э' && c == 'е') 'э' else if (h == 'э' && c == 'Е') 'Э' else c)
            }
            sb.toString()
        }
    }

